#!/usr/bin/env node
/**
 * Builds supabase/seed.sql from content/prompts/*.json (SRD §7).
 *
 *   node scripts/seed-prompts.mjs            write supabase/seed.sql
 *   node scripts/seed-prompts.mjs --check    validate the packs only
 *   node scripts/seed-prompts.mjs --push     replace the hosted project's prompts
 *
 * seed.sql is applied by `supabase db reset` locally. --push calls the
 * api_seed_prompts RPC using NEXT_PUBLIC_SUPABASE_URL, NEXT_PUBLIC_SUPABASE_ANON_KEY
 * and GPE_API_SECRET from the environment or .env.local.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'content/prompts');
const check = process.argv.includes('--check');
const push = process.argv.includes('--push');

function loadEnv() {
  const env = { ...process.env };
  const file = path.join(root, '.env.local');
  if (fs.existsSync(file)) {
    for (const line of fs.readFileSync(file, 'utf8').split('\n')) {
      const m = /^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/.exec(line);
      if (m && env[m[1]] == null) env[m[1]] = m[2].replace(/^['"]|['"]$/g, '');
    }
  }
  return env;
}

const quote = (s) => `'${String(s).replace(/'/g, "''")}'`;
const array = (list) => (list && list.length ? `array[${list.map(quote).join(', ')}]::text[]` : 'null');

const rows = [];
const records = [];
const problems = [];
for (const file of fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort()) {
  const game = file.replace(/\.json$/, '');
  const items = JSON.parse(fs.readFileSync(path.join(dir, file), 'utf8'));
  if (!Array.isArray(items) || items.length === 0) problems.push(`${file}: empty pack`);
  items.forEach((item, i) => {
    if (typeof item.text !== 'string' || !item.text.trim()) problems.push(`${file}[${i}]: missing text`);
    if (item.decoys != null && !Array.isArray(item.decoys)) problems.push(`${file}[${i}]: decoys must be an array`);
    records.push({ game, text: item.text, answer: item.answer ?? null, decoys: item.decoys ?? null, family_friendly: item.family_friendly !== false });
    rows.push(
      `(${quote(game)}, ${quote(item.text)}, ${item.answer == null ? 'null' : quote(item.answer)}, ${array(item.decoys)}, ${item.family_friendly === false ? 'false' : 'true'})`,
    );
  });
  console.log(`${game.padEnd(20)} ${items.length}`);
}

if (problems.length) {
  console.error(problems.join('\n'));
  process.exit(1);
}
if (check) process.exit(0);

if (push) {
  const env = loadEnv();
  const url = env.NEXT_PUBLIC_SUPABASE_URL;
  const key = env.NEXT_PUBLIC_SUPABASE_ANON_KEY;
  const secret = env.GPE_API_SECRET;
  if (!url || !key || !secret) {
    console.error('Set NEXT_PUBLIC_SUPABASE_URL, NEXT_PUBLIC_SUPABASE_ANON_KEY and GPE_API_SECRET.');
    process.exit(1);
  }
  const res = await fetch(`${url}/rest/v1/rpc/api_seed_prompts`, {
    method: 'POST',
    headers: { apikey: key, 'Content-Type': 'application/json' },
    body: JSON.stringify({ p_secret: secret, p_rows: records }),
  });
  const body = await res.text();
  if (!res.ok) {
    console.error(`Push failed (${res.status}): ${body}`);
    process.exit(1);
  }
  console.log(`\nPushed ${body} prompts to ${url}.`);
  process.exit(0);
}

const sql = `-- Generated by scripts/seed-prompts.mjs from content/prompts/*.json. Do not edit by hand.
begin;
delete from public.prompts;
insert into public.prompts (game, text, answer, decoys, family_friendly) values
${rows.join(',\n')};
commit;
`;
fs.writeFileSync(path.join(root, 'supabase/seed.sql'), sql);
console.log(`\nWrote supabase/seed.sql with ${rows.length} prompts.`);
